#!/usr/bin/env python3
"""MAP-003f: export validated V5 corporation maps for the game (godot/data/maps/map003_v5.json).

    python3 tools/map/export_maps.py            # write
    python3 tools/map/export_maps.py --check    # exit 1 if the committed file differs (CI)

Reuses the validated generator (prototypes/map/map003_generator.py, gen5 / v5_json) unchanged; this
file only selects seeds and serialises. Never edit the JSON by hand: regenerate it.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "prototypes", "map"))
import map003_generator as G  # noqa: E402

OUT = os.path.join(ROOT, "godot", "data", "maps", "map003_v5.json")
COUNT = 20   # the first 20 accepted seeds; the game picks one per run


def build():
    maps, seed = [], 0
    while len(maps) < COUNT:
        m = G.gen5(seed)
        seed += 1
        if m["status"] == "ok":
            maps.append(G.v5_json(m))
    return {"version": "V5", "decision": "MAP-003f",
            "about": "Generated by tools/map/export_maps.py from prototypes/map/map003_generator.py (gen5). Do not edit.",
            "maps": maps}


def text():
    return json.dumps(build(), ensure_ascii=False, indent="\t") + "\n"


def main():
    t = text()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != t:
            print("ERROR: %s is stale; run tools/map/export_maps.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("map003_v5.json: in step with the generator (%d maps)" % COUNT)
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(t)
    print("wrote %s (%d maps)" % (os.path.relpath(OUT, ROOT), COUNT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
